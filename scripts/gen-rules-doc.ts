// Purpose: read src/domain/**/rules.ts and write docs/rules/<entity>.md (function, summary, @ears tags).
// Usage: node scripts/gen-rules-doc.ts [--strict]. Plain regex parsing, only fs and path. Erasable TypeScript only.
// --strict exits 1 when an exported function or const arrow has no TSDoc block or no @ears tag. CI also runs git status on docs/rules to catch drift.
// Node may print MODULE_TYPELESS_PACKAGE_JSON when package.json has no "type": "module". The warning is harmless.
import { mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { basename, dirname, join } from 'node:path';

type Rule = { name: string; summary: string; ears: string[] };

function findRuleFiles(dir: string): string[] {
  let out: string[] = [];
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) out = out.concat(findRuleFiles(full));
    else if (entry === 'rules.ts') out.push(full);
  }
  return out;
}

function parseRules(source: string): { rules: Rule[]; undocumented: string[] } {
  const documented = /\/\*\*((?:(?!\*\/)[\s\S])*)\*\/\s*export\s+(?:async\s+)?(?:function\s+|const\s+)([A-Za-z0-9_]+)/g;
  const rules: Rule[] = [];
  let m: RegExpExecArray | null;
  while ((m = documented.exec(source)) !== null) {
    const text = (m[1] ?? '').split('\n').map((l) => l.replace(/^\s*\*\s?/, '')).join('\n').trim();
    const [head, ...tags] = text.split(/^@/m);
    const ears = tags.filter((t) => t.startsWith('ears')).map((t) => t.slice(4).replace(/\s+/g, ' ').trim());
    rules.push({ name: m[2] ?? '', summary: (head ?? '').replace(/\s+/g, ' ').trim(), ears });
  }
  const fns = /export\s+(?:async\s+)?function\s+([A-Za-z0-9_]+)/g;
  const arrows = /export\s+const\s+([A-Za-z0-9_]+)\s*(?::[^=]+)?=\s*(?:async\s+)?(?:\(|function\b|[A-Za-z0-9_]+\s*=>)/g;
  const all = [...source.matchAll(fns), ...source.matchAll(arrows)].map((x) => x[1] ?? '');
  const seen = new Set(rules.map((r) => r.name));
  return { rules, undocumented: all.filter((n) => !seen.has(n)) };
}

const cell = (s: string) => (s === '' ? '-' : s.replace(/\|/g, '\\|'));

function render(entity: string, rules: Rule[]): string {
  const rows = rules.map((r) => `| \`${r.name}\` | ${cell(r.summary)} | ${cell(r.ears.join('<br>'))} |`);
  return [
    `<!-- Generated by scripts/gen-rules-doc.ts from src/domain/${entity}/rules.ts. Do not edit. -->`,
    `# Rules: ${entity}`,
    '',
    '| Function | Summary | EARS |',
    '|---|---|---|',
    ...rows,
    '',
  ].join('\n');
}

const strict = process.argv.includes('--strict');
const root = 'src/domain';
let problems = 0;
let written = 0;
let files: string[] = [];
try {
  files = findRuleFiles(root);
} catch {
  console.log(`No ${root} folder. Nothing to generate.`);
}
for (const file of files) {
  const entity = basename(dirname(file));
  const { rules, undocumented } = parseRules(readFileSync(file, 'utf8'));
  for (const name of undocumented) {
    console.log(`WARN ${file}: ${name} has no TSDoc block`);
    problems++;
  }
  for (const r of rules.filter((x) => x.ears.length === 0)) {
    console.log(`WARN ${file}: ${r.name} has no @ears tag`);
    problems++;
  }
  mkdirSync('docs/rules', { recursive: true });
  writeFileSync(join('docs/rules', `${entity}.md`), render(entity, rules));
  written++;
}
console.log(`Wrote ${written} rules doc(s) to docs/rules/. Warnings: ${problems}.`);
if (strict && problems > 0) process.exit(1);
